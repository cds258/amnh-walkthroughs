// Skull builders. Skulls are built in normalised units (skull length = 1, snout towards +x, y up, symmetric in z)
// and return { bone: MB, ds: MB, origin: [x, y] } where origin is the occipital condyle (the joint with the neck).
//
// The workhorse is shellSkull(): the lateral outline of the skull (with the fenestrae as real holes) is
// triangulated, given thickness and bent into left and right side walls whose spacing follows a width profile;
// a roof ribbon closes the top. The mandible is made the same way and hinged at the jaw joint.
import * as THREE from 'three';
import { MB } from './mesh.js';
import { clamp, lerp, pw, prof, rad } from './engine.js';

/** min / max y of a closed outline at abscissa x */
function yRange(out, x) {
  let lo = Infinity, hi = -Infinity;
  for (let i = 0; i < out.length; i++) {
    const a = out[i], b = out[(i + 1) % out.length];
    const x0 = Math.min(a[0], b[0]), x1 = Math.max(a[0], b[0]);
    if (x < x0 - 1e-9 || x > x1 + 1e-9) continue;
    const y = Math.abs(b[0] - a[0]) < 1e-9 ? a[1] : a[1] + (b[1] - a[1]) * (x - a[0]) / (b[0] - a[0]);
    if (y < lo) lo = y; if (y > hi) hi = y;
    if (Math.abs(b[0] - a[0]) < 1e-9) { if (b[1] < lo) lo = b[1]; if (b[1] > hi) hi = b[1]; }
  }
  return [lo, hi];
}
function polyArea(r) { let a = 0; for (let i = 0; i < r.length; i++) { const p = r[i], q = r[(i + 1) % r.length]; a += p[0] * q[1] - q[0] * p[1]; } return a / 2; }
/** point at fraction t of a polyline's length */
function along(line, t) {
  let L = 0; const seg = [];
  for (let i = 1; i < line.length; i++) { const d = Math.hypot(line[i][0] - line[i - 1][0], line[i][1] - line[i - 1][1]); seg.push(d); L += d; }
  let s = clamp(t, 0, 1) * L;
  for (let i = 0; i < seg.length; i++) {
    if (s <= seg[i] || i === seg.length - 1) { const f = seg[i] ? s / seg[i] : 0; return [lerp(line[i][0], line[i + 1][0], f), lerp(line[i][1], line[i + 1][1], f)]; }
    s -= seg[i];
  }
  return line[line.length - 1];
}
/** ellipse outline helper for fenestrae: centre, radii, tilt (deg), n points, optional squash power */
export function ell(cx, cy, rx, ry, tilt = 0, n = 10) {
  const out = [], ct = Math.cos(rad(tilt)), st = Math.sin(rad(tilt));
  for (let i = 0; i < n; i++) {
    const a = (i / n) * Math.PI * 2, x = Math.cos(a) * rx, y = Math.sin(a) * ry;
    out.push([cx + x * ct - y * st, cy + x * st + y * ct]);
  }
  return out;
}

function teethRow(mb, ctx, T, zAt, dirY) {
  const n = T.n, tc = ctx.tooth();
  for (const s of [1, -1]) {
    for (let k = 0; k < n; k++) {
      const t = (k + 0.5) / n;
      const [x, y] = along(T.line, t);
      let len = prof(T.len, t) * (1 + ((k * 7919 + (s > 0 ? 3 : 5)) % 5 - 2) * (T.jit ?? 0.07));
      if (len < 0.004) continue;
      const r = len * (T.rk ?? 0.2);
      const z = s * (zAt(x, y) - (T.inset ?? 0.012));
      const back = (T.back ?? 0.2) * len, splay = (T.splay ?? 0) * len;
      const base = [x, y - dirY * len * 0.15, z];
      const tip = [x - back, y + dirY * len, z + s * splay];
      const mid = [x - back * 0.25 + len * 0.04, y + dirY * len * 0.5, z + s * splay * 0.5];
      const c = [tc[0] * (0.9 + 0.2 * ((k * 13) % 7) / 7), tc[1] * (0.9 + 0.2 * ((k * 13) % 7) / 7), tc[2] * (0.9 + 0.2 * ((k * 13) % 7) / 7)];
      const blunt = T.blunt ?? 0.001;
      mb.tube([base, mid, tip], [r, r * 0.72, r * blunt], [r * (T.flat ?? 1), r * 0.72 * (T.flat ?? 1), r * blunt], { radial: T.radial || 5, color: c, up: [1, 0, 0] });
    }
  }
}

/**
 * P: { out, holes, w: [[x, halfWidth]...], kTop (number | [[x,k]...]: width multiplier at the top edge), kPow,
 *   th, roof: [i0, i1] (outline index range closed by the roof ribbon), arch, roofSeg,
 *   brain: { c: [x,y], r: [rx,ry,rz] }, condyle: [x,y],
 *   teeth: { line, n, len, back, rk, inset, splay },
 *   jaw: { out, holes, joint: [x,y], wFront, pw, th, teeth, sym }, gape (deg),
 *   extra(bone, ds, h) }
 */
/** insert a Catmull-Rom midpoint on every edge of a closed outline (original points stay at even indices) */
function refine(r) {
  const n = r.length, o = [];
  for (let i = 0; i < n; i++) {
    const a = r[(i - 1 + n) % n], b = r[i], c = r[(i + 1) % n], d = r[(i + 2) % n];
    o.push(b, [(-a[0] + 9 * b[0] + 9 * c[0] - d[0]) / 16, (-a[1] + 9 * b[1] + 9 * c[1] - d[1]) / 16]);
  }
  return o;
}

export function shellSkull(ctx, P) {
  const bone = new MB(), ds = new MB();
  const c0 = ctx.jit(0.04, P.shade ?? 1);
  const sub = P.sub ?? 1;
  const out = sub ? refine(P.out) : P.out, holes = (P.holes || []).map((h) => (sub ? refine(h) : h));
  const kTop = (x) => pw(P.kTop ?? 0.6, x);
  const kp = P.kPow || 1.5;
  const W = (x, y) => {
    const [lo, hi] = yRange(out, x);
    const f = hi > lo + 1e-6 ? clamp((y - lo) / (hi - lo), 0, 1) : 0;
    return pw(P.w, x) * (1 - (1 - kTop(x)) * Math.pow(f, kp));
  };
  const th = P.th || 0.02;
  const cfn = P.colorFn ? (x, y) => { const k = P.colorFn(x, y); return [c0[0] * k, c0[1] * k, c0[2] * k]; } : null;
  for (const s of [1, -1]) {
    bone.poly(out, holes, (x, y, layer) => [x, y, s * Math.max(0.003, W(x, y) - layer * th)], { flip: s < 0, color: c0, colorFn: cfn });
  }
  // roof ribbon(s)
  const ccw = polyArea(out) > 0;
  const ribbons = P.roof ? (Array.isArray(P.roof[0]) ? P.roof : [P.roof]) : [];
  for (const [j0, j1] of ribbons) {
    const i0 = sub ? j0 * 2 : j0, i1 = sub ? j1 * 2 : j1;
    const rows = [], n = out.length, m = P.roofSeg || 5;
    const cnt = ((i1 - i0 + n) % n) + 1;
    for (let q = 0; q < cnt; q++) {
      const i = (i0 + q) % n;
      const a = out[(i - 1 + n) % n], b = out[(i + 1) % n], p = out[i];
      let tx = b[0] - a[0], ty = b[1] - a[1];
      const l = Math.hypot(tx, ty) || 1; tx /= l; ty /= l;
      const nx = ccw ? ty : -ty, ny = ccw ? -tx : tx;
      const Wv = W(p[0], p[1]);
      const arch = (typeof P.arch === 'function' ? P.arch(p[0], p[1]) : (P.arch ?? 0.3)) * Wv;
      const row = [];
      for (let j = 0; j <= m; j++) {
        const t = -Math.PI / 2 + Math.PI * j / m;
        row.push([p[0] + nx * arch * Math.cos(t), p[1] + ny * arch * Math.cos(t), Wv * Math.sin(t)]);
      }
      rows.push(row);
    }
    ds.grid(rows, { color: c0, flip: !ccw });
  }
  if (P.brain) bone.ellipsoid([P.brain.c[0], P.brain.c[1], 0], P.brain.r, { color: ctx.jit(0.03, 0.7), seg: 8, rings: 5 });
  const h = { W, th, ctx, c0 };
  if (P.teeth) for (const T of Array.isArray(P.teeth) ? P.teeth : [P.teeth]) teethRow(bone, ctx, T, (x, y) => W(x, y) - th * 0.5, -1);
  if (P.extra) P.extra(bone, ds, h);
  // mandible
  if (P.jaw) {
    const J = P.jaw, jb = new MB();
    const cj = ctx.jit(0.04, P.shade ?? 1);
    let xmax = -Infinity;
    for (const p of J.out) if (p[0] > xmax) xmax = p[0];
    const wBack = J.wBack ?? W(J.joint[0], J.joint[1]) - th * 0.5;
    const jth = J.th || 0.03;
    const zj = (x) => lerp(wBack, J.wFront ?? 0.03, Math.pow(clamp(x / xmax, 0, 1), J.pw || 1.6));
    const jout = sub ? refine(J.out) : J.out, jholes = (J.holes || []).map((h) => (sub ? refine(h) : h));
    for (const s of [1, -1]) {
      jb.poly(jout, jholes, (x, y, layer) => [x, y, s * Math.max(0.002, zj(x) + jth * 0.5 - layer * jth)], { flip: s < 0, color: cj });
    }
    if (J.sym !== false) {
      const [lo, hi] = yRange(J.out, xmax - 0.03);
      const wF = J.wFront ?? 0.03, hy = Math.max(0.01, (hi - lo) * 0.5), ym = (lo + hi) / 2;
      if (wF > 0.055) jb.tube([[xmax - 0.03, ym, -wF], [xmax - 0.005, ym, -wF * 0.6], [xmax + 0.012, ym, 0], [xmax - 0.005, ym, wF * 0.6], [xmax - 0.03, ym, wF]], jth * 0.6, hy, { radial: 6, color: cj, up: [0, 1, 0] });
      else jb.ellipsoid([xmax - 0.025, ym, 0], [0.035, hy, wF + jth * 0.6], { color: cj, seg: 6, rings: 4 });
    }
    if (J.teeth) for (const T of Array.isArray(J.teeth) ? J.teeth : [J.teeth]) teethRow(jb, ctx, T, (x) => zj(x), 1);
    if (J.extra) J.extra(jb, { zj, ctx, cj });
    const m = new THREE.Matrix4().makeTranslation(J.joint[0], J.joint[1], 0).multiply(new THREE.Matrix4().makeRotationZ(-rad(P.gape || 0)));
    bone.merge(jb, m);
  }
  return { bone, ds, origin: P.condyle || [0, 0] };
}

